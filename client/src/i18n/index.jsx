export function getInitialLanguage(storage = localStorage) {
  return readStoredLanguage(storage);
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);
  const setLanguage = (nextLanguage) => setLanguageState(normalizeLanguage(nextLanguage));

  useEffect(() => {
    persistLanguage(language, localStorage, document.documentElement);
    document.title = messages[language].metaTitle;
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute('content', messages[language].metaDescription);
  }, [language]);

  const value = useMemo(() => {
    const translate = (key, variables = {}) => {
      const template = messages[language][key] ?? messages['pt-PT'][key] ?? key;
      return Object.entries(variables).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, replacement),
        template
      );
    };
    const pluralize = (key, count, variables = {}) => {
      const category = new Intl.PluralRules(language).select(Number(count));
      const pluralKey = messages[language][`${key}_${category}`] !== undefined
        ? `${key}_${category}`
        : `${key}_other`;
      return translate(pluralKey, { ...variables, count });
    };
    return { language, setLanguage, t: translate, tp: pluralize };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage debe usarse dentro de LanguageProvider');
  return context;
}

export function formatVerificationDate(value, language) {
  if (!value) return null;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  return new Intl.DateTimeFormat(language, { dateStyle: 'medium' }).format(date);
}

